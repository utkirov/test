    private fun eye(x: Number, y: Number, look: Int = 1, angry: Boolean = false, blink: Boolean = false) {
        val xf = x.toFloat(); val yf = y.toFloat()
        if (blink) { px("#1c1410", xf, yf + 1, 3, 1); return }
        px("#ffffff", xf, yf, 3, 2); px("#1c1410", xf + 1 + look, yf, 1, 2)
        if (angry) px("#1c1410", xf - 1, yf - 1, 4, 1)
    }

